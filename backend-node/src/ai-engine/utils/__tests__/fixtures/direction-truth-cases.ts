/**
 * 方向真值 fixture —— 由**视觉裁判**判读设计稿截图得到（2026-10-27）
 *
 * ## 为什么这份 fixture 是「真值」而不是「另一套判据」
 *
 * 真值来源与产线判据**完全异源**：产线用「成对 side-by-side 占比」算方向，
 * 本 fixture 的真值来自 **Figma 设计稿导出图 mc-preview.png 的局部裁剪目视判读**
 * （24 张裁剪 + 一张 4×6 对照图，见 .workbuddy/reports/2026-10-27-direction-truth-cases.md）。
 * 判读走的是「人眼看排布」这一路，与几何聚类没有任何共享代码、共享中间量。
 *
 * ## 样本怎么来的（不是挑出来的）
 *
 * 采样池 = 「无 layoutMode ∧ ≥2 子 ∧ 产线判 low」= 777 个（含重复组件）；
 * 按节点 id 去重 32 个 → 按**结构签名**去重（父框舍入 20px + 子项尺寸/相对位置舍入 8px）
 * → 24 个唯一结构。即：这是**问题区（low 置信）里的全部结构种类**，不是抽样。
 * 其中 6 个是前几轮已人工确证的锚点（★）：565:3 / 48:5801 / 801:3 / 81:7 / 807:2 / 2:8419。
 *
 * ## 坐标怎么来的
 *
 * 全部 bbox 抄自真机语料 workspace/custom-components/<comp>/.checkpoint/figma.json 的
 * absoluteBoundingBox（父框 + 每个子项），不做任何缩放/归一 —— 与产线入参同口径：
 * 子项只传 { id, absoluteBoundingBox }（不带 type，与 buildNodeLayoutFacts 一致）。
 * 只保留 2 位小数（原值有 x.00003051757812 这类浮点尾巴，舍入不影响任何判据）。
 *
 * ## 判读规则（事前一刀切死；规则 3 已修正一次，见下）
 *
 * 1. 先把子项按 y 重叠归成「带」；
 * 2. 主轴 = 带的堆叠方向：≥2 条带 ⇒ column；只有 1 条带但子项沿 x 分开 ⇒ row；
 * 3. **全宽元素自成一带**，主轴看**带**的堆叠方向；既有多条带、带内又沿 x 分开且对齐 ⇒ grid；
 * 4. 🔴 装饰元素不算布局子项：细长条（<8px）、孤立极小图标（<10px）、半透明叠层
 *    （占满整宽的标题条 / 整块内容**不算**装饰）；
 * 5. 判不准填 ?，弃权样本不进阳性断言（宁缺勿滥）。
 *
 * ⚠️ 规则 3 的初版是错的：原写「全宽元素不参与主轴判定」，对 807:2 会先剔掉两个
 *    97% 宽元素、只剩底部小块 ⇒ 得出 row，而真值明明是三段纵向。改成「自成一带」后
 *    才与 6 个锚点全部自洽。**规则错一次就是这个后果，所以真值必须来自图、不来自推演。**
 *
 * ## 用途边界（重要）
 *
 * 本 fixture 只覆盖 low 置信这批「产线靠猜」的容器，**不覆盖**有 layoutMode 的 2164 个干净样本。
 * 它只回答一个问题：**换度量会不会比现产线更准？**实测答案见 spec 断言。
 *
 * ## ⚠️ 二次复核（2026-10-27 同日，改判 1 例）
 *
 * 首轮判读是在 4×6 对照图上做的，格子小；改用 3× 放大的单张裁剪逐例复核时发现
 * **`2:3446` 判错了**：它是「标题带（江阴靖江长江隧道，y=2..27）在上、内容带
 * （客车 22350 / 环形图 / 货车 16270，y=31..111）在下」⇒ 容器直接子项是**纵排**，
 * 真值应为 `column` 而不是 `row`。已改正。
 * ⇒ 教训：**对照图只用于初筛，定稿必须逐张看放大图**。一张拼图里的错判会连带整份结论失真：
 *   首轮把产线算成 21/22 = 95.5%，改正后是 **20/22 = 90.9%**；而且「宽容器真纵排」
 *   这个缺陷看起来只有 1 例，实际是 **2 例 / 57 个容器实例**（全语料仅 3 种结构）。
 */
